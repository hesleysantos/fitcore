const cache = new Map();
const FALLBACK = { view: 'side', frames: [stand(), stand()], equip: [], missing: true };

export function hasAnim(id) { return !!M[id]; }

export function animFor(ex) {
  const id = typeof ex === 'string' ? ex : ex.id;
  if (cache.has(id)) return cache.get(id);
  const m = M[id];
  const anim = m ? m[0](m[1] || {}) : FALLBACK;
  if (MAOS[id] && !anim.maos) anim.maos = MAOS[id];
  cache.set(id, anim);
  return anim;
}
